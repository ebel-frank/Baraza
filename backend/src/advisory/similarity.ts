/**
 * Cosine similarity computed in application code rather than a DB-native
 * vector search — the seeded corpus is a handful of documents, so scanning
 * all chunks in memory is plenty fast and works with any MongoDB instance
 * (no dependency on Atlas Vector Search or similar).
 */
export function cosineSimilarity(a: number[], b: number[]): number {
  let dot = 0;
  let normA = 0;
  let normB = 0;
  for (let i = 0; i < a.length; i++) {
    dot += a[i] * b[i];
    normA += a[i] * a[i];
    normB += b[i] * b[i];
  }
  if (normA === 0 || normB === 0) return 0;
  return dot / (Math.sqrt(normA) * Math.sqrt(normB));
}
